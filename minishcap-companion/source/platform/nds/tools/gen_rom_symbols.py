#!/usr/bin/env python3
"""Replace the ROM-copy stubs in src/port/data_const_stubs.c with linker symbols.

On the NDS the cart ROM is mapped flat at 0x08000000 (Slot-2), so a stub of ROM bytes at
offset OFF is already present at address 0x08000000 + OFF. Emitting `NAME = 0x08000000+OFF;`
lets the linker resolve every reference to the cart and frees ~1 MB of the 4 MB RAM.

  gen_rom_symbols.py data_const_stubs.c rom_symbols.ld kept_stubs.c [--rom baserom.gba]

--rom verifies each stub's bytes against the ROM first (stubs are USA-region data).
Stubs whose ROM offset is not 4-byte aligned stay as RAM copies (kept_stubs.c): the originals are
aligned(4), so code may read them as halfwords/words, which an unaligned cart address would break.
rom_symbols.ld contains only names and offsets; kept_stubs.c is derived ROM data and is not committed.
"""
import argparse
import re
import sys

BLOCK = re.compile(
    r"/\* (\w+) @ ROM 0x([0-9A-Fa-f]+), (\d+) bytes \*/\s*\n"
    r"const u8 (\w+)\[(\d+)\][^=]*=\s*\{(.*?)\};",
    re.S,
)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("stubs")
    ap.add_argument("out")
    ap.add_argument("kept")
    ap.add_argument("--rom")
    a = ap.parse_args()
    src = open(a.stubs).read()
    rom = open(a.rom, "rb").read() if a.rom else None
    lines, kept, total, bad, unaligned = [], [], 0, 0, 0
    for m in BLOCK.finditer(src):
        label, off, size, name, n, body = m.groups()
        off, size = int(off, 16), int(size)
        assert int(n) == size, name
        if rom is not None:
            data = bytes(int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", body))
            if len(data) != size or rom[off : off + size] != data:
                print(f"MISMATCH {name} @ 0x{off:X}", file=sys.stderr)
                bad += 1
        if off % 4:
            unaligned += 1
            kept.append(m.group(0))
            continue
        total += size
        lines.append(f"{name} = 0x{0x08000000 + off:08X};")
    if not lines:
        sys.exit("no stubs found")
    if bad:
        sys.exit(f"{bad} stubs differ from the ROM; refusing to emit")
    with open(a.out, "w") as f:
        f.write("/* Generated by tools/gen_rom_symbols.py - do not edit. Cart ROM is mapped at 0x08000000. */\n")
        f.write("\n".join(lines) + "\n")
    with open(a.kept, "w") as f:
        f.write("/* Generated by tools/gen_rom_symbols.py: stubs kept in RAM (unaligned cart offsets). */\n")
        f.write("#include <stdint.h>\ntypedef uint8_t u8;\n\n" + "\n\n".join(kept) + "\n")
    print(f"{len(lines)} symbols, {total // 1024} KB freed, {unaligned} kept in RAM (unaligned)"
          + (", verified against ROM" if rom else ""))


main()
