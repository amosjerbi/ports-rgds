#!/usr/bin/env python3
"""Generate gba_layout.h: GBA RAM addresses (decomp linker.ld) + 32-bit field offsets (layout_probe.c asm).

  gen_layout.py <linker.ld> <layout_probe.s> <out.h>
Addresses come from the explicit `. = 0xOFF; sym = .;` lines of the decomp's linker script (USA).
"""
import re
import sys

ld, asm, out = sys.argv[1:4]
src = open(ld).read()
syms, cur = {}, None
for line in src.split("\n"):
    m = re.match(r"\s*(ewram|iwram)\s*\(NOLOAD\)", line)
    if m:
        cur = m.group(1)
        continue
    if cur and line.strip().startswith("}"):
        cur = None
    m = re.match(r"\s*\. = 0x([0-9A-Fa-f]+); (\w+) = \.;", line)
    if m and cur:
        syms.setdefault(m.group(2), (0x02000000 if cur == "ewram" else 0x03000000) + int(m.group(1), 16))

vals, label = {}, None
for line in open(asm):
    s = line.strip()
    m = re.match(r"(probe_\w+):", s)
    if m:
        label = m.group(1)
        continue
    m = re.match(r"\.word\s+(\d+)", s)
    if m and label:
        vals[label] = int(m.group(1))
        label = None
    elif label and re.match(r"\.(space|zero|skip)\b", s):
        vals[label] = 0 # a zero offset is emitted as .bss storage, not a .word
        label = None

want = ["gMain", "gUI", "gSave", "gRoomControls", "gPlayerEntity", "gPlayerState", "gArea", "gHUD"]
with open(out, "w") as f:
    f.write("/* Generated by tools/gen_layout.py - do not edit. USA GBA RAM map + 32-bit struct offsets. */\n#pragma once\n")
    for w in want:
        f.write(f"#define GBA_ADDR_{w} 0x{syms[w]:08X}u\n")
    f.write("#define GBA_ADDR_gSaveHeader 0x02000000u /* save.h: gSaveHeader is the start of EWRAM */\n")
    for k, v in sorted(vals.items()):
        f.write(f"#define GBA_{k[len('probe_'):]} {v}u\n")
print(f"{len(want)} addresses, {len(vals)} offsets")
