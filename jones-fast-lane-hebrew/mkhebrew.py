#!/usr/bin/env python3
"""Generate the Hebrew top-screen data (make he / make cd-he).

    python3 tools/mkhebrew.py tools/hebrew.tsv out.c [preview.png]

Writes a C file with
  - a small pixel font for the 27 Hebrew letters (ISO-8859-8 0xE0..0xFA) in two sizes matching the game's
    fonts 0 (8 px) and 1 (12 px),
  - the English -> Hebrew table from hebrew.tsv, Hebrew encoded as ISO-8859-8 (one byte per letter).
"""
import re
import sys

# 5-px-wide letters on an 8-row cell: row 0 is the ascender (lamed), rows 1-6 the body, row 7 descenders.
# Rows are listed from row 0; missing rows are blank. Narrow letters are simply shorter strings.
SMALL = {
    'א': [".....", "#...#", ".#..#", "..##.", ".#.#.", ".#..#", "##..#"],
    'ב': [".....", "####.", "...#.", "...#.", "...#.", "...#.", "#####"],
    'ג': ["....", "###.", "..#.", "..#.", "..#.", ".#.#", "#..#"],
    'ד': [".....", "#####", "...#.", "...#.", "...#.", "...#.", "...#."],
    'ה': [".....", "#####", "....#", "#...#", "#...#", "#...#", "#...#"],
    'ו': ["..", "##", ".#", ".#", ".#", ".#", ".#"],
    'ז': ["....", "####", ".#..", ".#..", ".#..", ".#..", ".#.."],
    'ח': [".....", "#####", "#...#", "#...#", "#...#", "#...#", "#...#"],
    'ט': [".....", "#..##", "#.#.#", "#...#", "#...#", "#...#", "#####"],
    'י': ["..", "##", ".#", ".#"],
    'ך': [".....", "#####", "....#", "....#", "....#", "....#", "....#", "....#"],
    'כ': [".....", "####.", "....#", "....#", "....#", "....#", "####."],
    'ל': ["#....", "#....", "#####", "....#", "....#", "...#.", "..#.."],
    'ם': [".....", "#####", "#...#", "#...#", "#...#", "#...#", "#####"],
    'מ': [".....", "#.##.", "##..#", "#...#", "#...#", "#...#", "#.###"],
    'ן': ["..", "##", ".#", ".#", ".#", ".#", ".#", ".#"],
    'נ': ["...", "##.", ".#.", ".#.", ".#.", ".#.", "###"],
    'ס': [".....", "####.", "#...#", "#...#", "#...#", "#...#", ".###."],
    'ע': [".....", "#...#", "#...#", "#...#", ".#..#", "..##.", "##..."],
    'ף': [".....", "#####", "#...#", "##..#", "....#", "....#", "....#", "....#"],
    'פ': [".....", "#####", "#...#", "##..#", "....#", "....#", "#####"],
    'ץ': [".....", "#...#", ".#..#", "..##.", "..#..", "..#..", "..#..", "..#.."],
    'צ': [".....", "#...#", ".#..#", "..##.", "...#.", "....#", "#####"],
    'ק': [".....", "#####", "....#", "#...#", "#...#", "#..#.", "#....", "#...."],
    'ר': [".....", "####.", "....#", "....#", "....#", "....#", "....#"],
    'ש': [".....", "#.#.#", "#.#.#", "#.#.#", "#.#.#", "#.##.", "####."],
    'ת': [".....", "#####", ".#..#", ".#..#", ".#..#", ".#..#", "##..#"],
}
LETTERS = "אבגדהוזחטיךכלםמןנסעףפץצקרשת"
assert len(LETTERS) == 27 and set(LETTERS) == set(SMALL)


def big(rows):
    """12-px font version: body 7 rows (row 3 doubled) and 1 px wider (the middle column doubled) so it sits
    with the game's larger, lighter font; ascender row 0, body rows 1-7 (baseline as the Latin capitals)."""
    w = len(rows[0])
    rows = [r.ljust(w, '.') for r in rows] + ['.' * w] * (8 - len(rows))
    rows = rows[:4] + [rows[3]] + rows[4:]
    if w >= 4:
        m = w // 2
        rows = [r[:m + 1] + r[m:] for r in rows]
    return rows


def glyph_c(rows):
    w = max(len(r) for r in rows)
    while rows and set(rows[-1]) <= {'.'}:
        rows = rows[:-1]
    out = []
    for r in rows:
        r = r.ljust(w, '.')
        v = 0
        for i, ch in enumerate(r):
            if ch == '#':
                v |= 0x80 >> (i + 1)          # column 0 left blank: letter spacing
        out.append(v)
    return w + 1, out


def norm(s):
    s = s.replace('|', ' ').replace('~', ' ').replace('\n', ' ')
    s = re.sub(r' +', ' ', s).strip()
    return s.rstrip(' .')


def cstr(b):
    out = '"'
    for c in b:
        if c == 0x22 or c == 0x5C:
            out += '\\' + chr(c)
        elif 0x20 <= c < 0x7F:
            out += chr(c)
        else:
            out += '\\%03o' % c
    return out + '"'


def main():
    tsv, out = sys.argv[1], sys.argv[2]
    pairs = {}
    for n, line in enumerate(open(tsv, encoding='utf-8'), 1):
        line = line.rstrip('\n')
        if not line or line.startswith('#'):
            continue
        if '\t' not in line:
            sys.exit(f"{tsv}:{n}: no tab")
        en, he = line.split('\t', 1)
        en, he = norm(en), he.strip()
        if en.count('%') != he.count('%'):
            sys.exit(f"{tsv}:{n}: %-fields differ")
        try:
            heb = he.encode('iso8859_8')
        except UnicodeEncodeError as e:
            sys.exit(f"{tsv}:{n}: not ISO-8859-8: {e}")
        pairs[en.encode('latin1')] = heb
    exact = sorted((k, v) for k, v in pairs.items() if b'%' not in k)
    pats = [(k, v) for k, v in pairs.items() if b'%' in k]

    o = ["/* Generated by tools/mkhebrew.py from tools/hebrew.tsv -- do not edit. */",
         '#include "hebrew.h"', ""]
    for name, conv in (("small", lambda r: r), ("big", big)):
        o.append(f"const HeGlyph he_font_{name}[27] = {{")
        for L in LETTERS:
            w, rows = glyph_c(conv(SMALL[L]))
            o.append(f"    {{ {w}, {len(rows)}, {{ {', '.join('0x%02x' % v for v in rows)} }} }},")
        o.append("};")
        o.append("")
    o.append(f"const int he_nexact = {len(exact)};")
    o.append("const HePair he_exact[] = {")
    o += [f"    {{ {cstr(k)}, {cstr(v)} }}," for k, v in exact]
    o.append("};")
    o.append(f"const int he_npat = {len(pats)};")
    o.append("const HePair he_pat[] = {")
    o += [f"    {{ {cstr(k)}, {cstr(v)} }}," for k, v in pats]
    o.append("};")
    open(out, 'w').write('\n'.join(o) + '\n')

    if len(sys.argv) > 3:                 # preview sheet of both sizes
        from PIL import Image
        img = Image.new('RGB', (27 * 9 * 4, 2 * 14 * 4), (24, 32, 64))
        for si, conv in enumerate((lambda r: r, big)):
            for i, L in enumerate(reversed(LETTERS)):
                rows = conv(SMALL[L])
                for y, r in enumerate(rows):
                    for x, ch in enumerate(r):
                        if ch == '#':
                            for a in range(4):
                                for b in range(4):
                                    img.putpixel(((i * 9 + 1 + x) * 4 + a, (si * 14 + 1 + y) * 4 + b), (240, 240, 240))
        img.save(sys.argv[3])


main()
